const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const fixture=JSON.parse(readFileSync('tests/fixtures/realistic-plan.json','utf8'));
const context=vm.createContext({assert,console,fixture,crypto:require('node:crypto').webcrypto});
for(const file of ['data.js','utils.js','employee.js','calculator.js']) vm.runInContext(readFileSync(file,'utf8'),context);
vm.runInContext(`
const period=new EmployeePeriod(2026,11);
period.salaryGoal.desired=fixture.input.desired;
period.workHours=fixture.input.hours;
period.workDays=fixture.input.shifts;
Object.assign(period.salaryGoal.realistic,fixture.input);
const result=SalaryCalculator.calculateRealisticPlan(period);
assert.equal(result.errors.length,0);
for(const key of ['salary','neededBonus','projected','remaining','credit','creditPerShift']) assert.equal(result[key],fixture.expected[key],key);
for(const line of result.lines) assert.equal(line.quantity,fixture.expected.quantities[line.key],line.key);
assert.equal(EmployeePeriod.fromJSON(period.toJSON()).workHours,178);
// Previously saved plan overrides must never replace the working-time fields.
period.salaryGoal.realistic.hours=1;
period.salaryGoal.realistic.shifts=1;
assert.equal(SalaryCalculator.calculateRealisticPlan(period).salary,17800);
assert.equal(SalaryCalculator.calculateRealisticPlan(period).lines.find(l=>l.key==='sim').quantity,60);
period.workHours=183;
assert.equal(SalaryCalculator.calculateRealisticPlan(period).salary,18300);
period.workHours=178;
period.salaryGoal.desired=1000000;
const huge=SalaryCalculator.calculateRealisticPlan(period);
assert.equal(huge.lines.find(l=>l.key==='sim').quantity,60);
assert.equal(huge.lines.find(l=>l.key==='mnp').quantity,8);
assert(huge.remaining>900000);
period.workDays=0;
assert(SalaryCalculator.calculateRealisticPlan(period).errors.length>0);
period.workDays=20;
period.salaryGoal.realistic.simShare=50;
assert(SalaryCalculator.calculateRealisticPlan(period).errors.some(e=>e.includes('100%')));
period.salaryGoal.realistic.simShare=35;
period.salaryGoal.realistic.multiplier=0;
assert(SalaryCalculator.calculateRealisticPlan(period).errors.length>0);
period.salaryGoal.realistic.multiplier=1;
period.salaryGoal.desired=10000;
const low=SalaryCalculator.calculateRealisticPlan(period);
assert.equal(low.remaining,0);
assert.equal(low.lines.find(l=>l.key==='sim').quantity,0);
period.salaryGoal.desired=50000;
period.salaryGoal.realistic.admin=2000;
const withAdmin=SalaryCalculator.calculateRealisticPlan(period);
assert.equal(withAdmin.neededBonus,30200);
assert.equal(withAdmin.projected,withAdmin.salary+2000+withAdmin.bonus);
period.salaryGoal.rates.sim=240;
assert.equal(SalaryCalculator.calculateRealisticPlan(period).rates.sim,240);
period.salaryGoal.rates.sim=null;
period.cityId='berezniki';
assert.equal(SalaryCalculator.calculateRealisticPlan(period).rates.sim,120);
period.month=12;
assert.equal(SalaryCalculator.calculateRealisticPlan(period).rates.application,0);
period.month=1;
assert.equal(SalaryCalculator.calculateRealisticPlan(period).factor,1.1);
const tracked=new EmployeePeriod(2026,11);
tracked.workHours=178;
tracked.workDays=20;
tracked.salaryGoal.desired=50000;
Object.assign(tracked.salaryGoal.realistic,fixture.input);
tracked.kpi={sim:100,conversion:100,focusSpd:100,focusCs:100,focusMnp:100,credits:85,accessories:85,insurance:85};
tracked.getDay(1).hours=10;
tracked.getDay(1).addItem(BLOCKS.OPERATOR,'base_tp',2);
tracked.getDay(1).addItem(BLOCKS.OPERATOR,'high_bundle_tp',3);
tracked.getDay(1).addItem(BLOCKS.SALES,'accessories',10000);
tracked.getDay(2).comment='This comment alone is not a worked shift';
const trackedPlan=SalaryCalculator.calculateRealisticPlan(tracked);
let progress=SalaryCalculator.calculatePlanProgress(tracked,trackedPlan);
assert.equal(progress.completedShifts,1);
assert.equal(progress.remainingShifts,19);
assert.equal(progress.earned,2296);
assert.equal(progress.salaryRemaining,47704);
assert.equal(progress.neededEarningsPerShift,2511);
assert.equal(progress.lines.find(l=>l.key==='sim').actual,5);
assert.equal(progress.lines.find(l=>l.key==='sim').remaining,55);
assert.equal(progress.lines.find(l=>l.key==='sim').neededPerShift,3);
assert.equal(progress.lines.find(l=>l.key==='accessories').remaining,60000);
tracked.salaryGoal.realistic.completedShifts=10;
progress=SalaryCalculator.calculatePlanProgress(tracked,trackedPlan);
assert.equal(progress.remainingShifts,10);
assert.equal(progress.neededEarningsPerShift,4771);
assert.equal(EmployeePeriod.fromJSON(tracked.toJSON()).salaryGoal.realistic.completedShifts,10);
tracked.salaryGoal.realistic.completedShifts=20;
progress=SalaryCalculator.calculatePlanProgress(tracked,trackedPlan);
assert.equal(progress.neededEarningsPerShift,null);
tracked.getDay(1).addItem(BLOCKS.OPERATOR,'high_bundle_tp',100);
progress=SalaryCalculator.calculatePlanProgress(tracked,trackedPlan);
assert.equal(progress.lines.find(l=>l.key==='sim').remaining,0);
assert.equal(progress.lines.find(l=>l.key==='sim').neededPerShift,0);
tracked.salaryGoal.realistic.completedShifts=21;
assert(SalaryCalculator.calculateRealisticPlan(tracked).errors.length>0);
console.log('Realistic planner: Excel fixture, caps, validation, persistence, seasonality and incentive expiry passed');
`,context);
